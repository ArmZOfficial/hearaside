"""Generates plugins/common/ui/Theme.h, web/site/src/styles/tokens.css and the Rust UI theme
(rust/crates/hs-ui/src/theme.rs + ui/theme.slint) from design/tokens.json.

    python design/gen_theme.py           # write every output
    python design/gen_theme.py --check   # exit 1 if an output is out of date or a text colour fails contrast (CTest / CI)
    python design/gen_theme.py --contrast  # only the WCAG contrast check (docs/ux-roadmap.md, 6.2)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "design" / "tokens.json"
OUT = ROOT / "plugins" / "common" / "ui" / "Theme.h"
CSS_OUT = ROOT / "web" / "site" / "src" / "styles" / "tokens.css"
HS_UI = ROOT / "rust" / "crates" / "hs-ui"
RS_OUT = HS_UI / "src" / "theme.rs"
SLINT_OUT = HS_UI / "ui" / "theme.slint"


def argb(value: str) -> str:
    value = value.strip()
    m = re.fullmatch(r"#([0-9a-fA-F]{6})", value)
    if m:
        return "0xff" + m.group(1).lower()
    m = re.fullmatch(r"rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)", value)
    if m:
        r, g, b = (int(m.group(i)) for i in range(1, 4))
        a = round(float(m.group(4)) * 255)
        return f"0x{a:02x}{r:02x}{g:02x}{b:02x}"
    raise ValueError(f"unsupported colour: {value}")


def generate() -> str:
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    if light.keys() != dark.keys():
        raise ValueError("light and dark palettes must define the same tokens")
    names = list(light.keys())

    out = [
        "// GENERATED by design/gen_theme.py from design/tokens.json - do not edit by hand.",
        "#pragma once",
        "",
        "#include <juce_graphics/juce_graphics.h>",
        "",
        "namespace hearaside::theme {",
        "",
        "struct Palette {",
    ]
    out += [f"    juce::Colour {n};" for n in names]
    out += ["};", ""]
    for label, pal in (("light", light), ("dark", dark)):
        out.append(f"inline const Palette& {label}() {{")
        out.append("    static const Palette p {")
        out += [f"        juce::Colour({argb(pal[n])}u),   // {n}" for n in names]
        out.append("    };")
        out.append("    return p;")
        out.append("}")
        out.append("")
    for group in ("radius", "space", "type", "glass", "motion", "layout"):
        out.append(f"namespace {group} {{")
        for k, v in t[group].items():
            if k.startswith("$"):
                continue
            out.append(f"constexpr float {k} = {float(v)!r}f;")
        out.append("}")
        out.append("")
    out.append("} // namespace hearaside::theme")
    return "\n".join(out) + "\n"


RATIOS = {"alphaDefault", "alphaMin", "alphaMax", "screenFit"}   # numbers without a unit (px)
MODULE_NAMES = {"type": "typography"}   # `type` is a Rust keyword


def rgba_parts(value: str):
    n = int(argb(value), 16)
    return (n >> 16) & 255, (n >> 8) & 255, n & 255, (n >> 24) & 255


def snake(name: str, upper: bool = False) -> str:
    out = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return out.upper() if upper else out.lower()


def kebab(name: str) -> str:
    return snake(name).replace("_", "-")


def number_groups(t):
    return [(g, [(k, v) for k, v in t[g].items() if not k.startswith("$")]) for g in ("radius", "space", "type", "glass", "motion", "layout")]


def generate_rs() -> str:
    """theme.rs of hs-ui: the palettes and numbers of Theme.h as consts."""
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    if light.keys() != dark.keys():
        raise ValueError("light and dark palettes must define the same tokens")
    names = list(light.keys())
    out = [
        "// GENERATED by design/gen_theme.py from design/tokens.json - do not edit by hand.",
        "//! Design tokens (colours, radii, spacing, type sizes, glass, motion, layout) of the HEARASIDE UI.",
        "",
        "/// 8-bit straight-alpha colour.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Rgba {",
        "    pub r: u8,",
        "    pub g: u8,",
        "    pub b: u8,",
        "    pub a: u8,",
        "}",
        "",
        "const fn c(r: u8, g: u8, b: u8, a: u8) -> Rgba {",
        "    Rgba { r, g, b, a }",
        "}",
        "",
        "/// One theme (light or dark): every colour token of `tokens.json`.",
        "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
        "pub struct Palette {",
    ]
    out += [f"    pub {snake(n)}: Rgba," for n in names]
    out += ["}", "", "impl Palette {", "    /// `(name in tokens.json, colour)` for every token, in file order.", f"    pub fn fields(&self) -> [(&'static str, Rgba); {len(names)}] {{", "        ["]
    out += [f'            ("{n}", self.{snake(n)}),' for n in names]
    out += ["        ]", "    }", "}", ""]
    for label, pal in (("LIGHT", light), ("DARK", dark)):
        out.append(f"pub const {label}: Palette = Palette {{")
        for n in names:
            r, g, b, a = rgba_parts(pal[n])
            out.append(f"    {snake(n)}: c({r}, {g}, {b}, {a}),")
        out.append("};")
        out.append("")
    out += ["/// The palette of a theme.", "pub const fn palette(dark: bool) -> &'static Palette {", "    if dark { &DARK } else { &LIGHT }", "}", ""]
    numbers = []
    for group, items in number_groups(t):
        out.append(f"pub mod {MODULE_NAMES.get(group, group)} {{")
        for k, v in items:
            out.append(f"    pub const {snake(k, True)}: f32 = {float(v)!r};")
            numbers.append((group, k, v))
        out.append("}")
        out.append("")
    out.append("/// `(group, name, value)` of every number above, named as in tokens.json (the in-sync test reads this).")
    out.append(f"pub const NUMBERS: [(&str, &str, f32); {len(numbers)}] = [")
    out += [f'    ("{g}", "{k}", {float(v)!r}),' for g, k, v in numbers]
    out.append("];")
    return "\n".join(out) + "\n"


def slint_colour(value: str) -> str:
    r, g, b, a = rgba_parts(value)
    return f"#{r:02x}{g:02x}{b:02x}" + ("" if a == 255 else f"{a:02x}")


def generate_slint() -> str:
    """theme.slint of hs-ui: Palette (one `dark` switch), Tokens (the numbers) and Motion (durations that drop to 0 with reduce-motion)."""
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    out = [
        "// GENERATED by design/gen_theme.py from design/tokens.json - do not edit by hand.",
        "",
        "export global Palette {",
        "    in property <bool> dark;",
    ]
    out += [f"    out property <color> {kebab(n)}: dark ? {slint_colour(dark[n])} : {slint_colour(light[n])};" for n in light]
    out += ["}", "", "export global Tokens {"]
    for group, items in number_groups(t):
        if group == "motion":
            continue
        for k, v in items:
            ratio = k in RATIOS
            out.append(f"    out property <{'float' if ratio else 'length'}> {group}-{kebab(k)}: {float(v)!r}{'' if ratio else 'px'};")
    out += ["}", "", "export global Motion {", "    in property <bool> reduce;"]
    for k, v in t["motion"].items():
        if k.startswith("$"):
            continue
        if k.endswith("Ms"):
            out.append(f"    out property <duration> {kebab(k)}: reduce ? 0ms : {int(v)}ms;")
        else:
            out.append(f"    out property <float> {kebab(k)}: {float(v)!r};")
    out.append("}")
    return "\n".join(out) + "\n"


def css_colour(value: str) -> str:
    return value.strip()


def generate_css() -> str:
    """tokens.css for the website: the same palette as the plug-ins, as CSS variables, plus the
    Tailwind v4 @theme mapping so utility classes use the tokens (no raw colours in classNames)."""
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    light, dark = t["color"]["light"], t["color"]["dark"]
    out = ["/* GENERATED by design/gen_theme.py from design/tokens.json - do not edit by hand. */", ""]
    out.append(":root {")
    out += [f"  --hs-{n}: {css_colour(v)};" for n, v in light.items()]
    out.append("  color-scheme: light;")
    out.append("}")
    out.append("")
    dark_vars = [f"  --hs-{n}: {css_colour(v)};" for n, v in dark.items()]
    out.append(':root[data-theme="dark"] {')
    out += dark_vars
    out.append("  color-scheme: dark;")
    out.append("}")
    out.append("")
    out.append("@media (prefers-color-scheme: dark) {")
    out.append('  :root:not([data-theme="light"]) {')
    out += ["  " + v for v in dark_vars]
    out.append("    color-scheme: dark;")
    out.append("  }")
    out.append("}")
    out.append("")
    out.append("@theme inline {")
    out += [f"  --color-{n}: var(--hs-{n});" for n in light.keys()]
    for k, v in t["radius"].items():
        if not k.startswith("$"):
            out.append(f"  --radius-{k}: {v}px;")
    out.append("  --font-sans: 'Anuphan', system-ui, -apple-system, 'Segoe UI', sans-serif;")
    out.append("}")
    return "\n".join(out) + "\n"


def parse_colour(value: str):
    v = argb(value)
    n = int(v, 16)
    return [((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255, ((n >> 24) & 255) / 255]


def over(top, bottom):
    a = top[3]
    return [top[i] * a + bottom[i] * (1 - a) for i in range(3)] + [1.0]


def luminance(c) -> float:
    f = lambda x: x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(c[0]) + 0.7152 * f(c[1]) + 0.0722 * f(c[2])


def contrast_ratio(a, b) -> float:
    la, lb = luminance(a), luminance(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


def contrast_problems() -> list:
    """WCAG contrast of every text token on every background, both themes (section 6.2)."""
    t = json.loads(TOKENS.read_text(encoding="utf-8"))
    rules = t["contrast"]
    problems = []
    for mode in ("light", "dark"):
        pal = {k: parse_colour(v) for k, v in t["color"][mode].items()}

        def layer(stack: str):
            names = stack.split(">")
            colour = pal[names[-1]]
            for n in reversed(names[:-1]):
                colour = over(pal[n], colour)
            return colour

        pairs = [(fg, bg) for fg in rules["text"] for bg in rules["backgrounds"]] + [tuple(p) for p in rules["pairs"]]
        for fg, bg in pairs:
            back = layer(bg)
            ratio = contrast_ratio(over(pal[fg], back), back)
            if ratio < rules["minRatio"]:
                problems.append(f"{mode}: {fg} on {bg} = {ratio:.2f}:1 (needs {rules['minRatio']}:1)")
    for name in rules["disabledOnly"]:
        if name in rules["text"]:
            problems.append(f"{name} is listed as disabled-only and as text")
    return problems


def main() -> int:
    text = generate()
    if "--contrast" in sys.argv or "--check" in sys.argv:
        problems = contrast_problems()
        for p in problems:
            print("contrast:", p)
        if problems:
            return 1
        print("contrast: every text token reaches the minimum ratio in both themes")
        if "--contrast" in sys.argv:
            return 0
    outputs = ((OUT, text), (CSS_OUT, generate_css()), (RS_OUT, generate_rs()), (SLINT_OUT, generate_slint()))
    if "--check" in sys.argv:
        for path, want in outputs:
            current = path.read_text(encoding="utf-8") if path.exists() else ""
            if current.replace("\r\n", "\n") != want:
                print(f"{path.relative_to(ROOT)} is out of date - run python design/gen_theme.py")
                return 1
        print("Theme.h, tokens.css, theme.rs and theme.slint are in sync with tokens.json")
        return 0
    for path, want in outputs:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(want, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
