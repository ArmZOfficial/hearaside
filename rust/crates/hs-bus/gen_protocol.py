# Regenerates src/protocol.rs from protocol.h and the v14 layout fixture (explicit padding).
#   python rust/crates/hs-bus/gen_protocol.py . rust/crates/hs-bus/src/protocol.rs   (from the repo root, then cargo fmt)
import json, re, sys
root = sys.argv[1]
hdr = open(f'{root}/libs/ssbus/include/ssbus/protocol.h').read()
fix = json.load(open(f'{root}/compat/fixtures/shm-v14-layout.json'))
consts = fix['constants']

def snake(n):
    s = re.sub(r'(?<=[a-z0-9])([A-Z])', r'_\1', n).lower()
    return s.replace('a_r_g_b', 'argb')

prim = {'uint32_t': 'u32', 'int32_t': 'i32', 'uint64_t': 'u64', 'int64_t': 'i64', 'float': 'f32', 'char': 'u8'}
atom = {'uint32_t': 'AtomicU32', 'int32_t': 'AtomicI32', 'uint64_t': 'AtomicU64', 'int64_t': 'AtomicI64'}

def dim(expr):
    expr = expr.strip()
    if expr in consts: return str(consts[expr])
    if not re.fullmatch(r"[\w\s/]+", expr) or re.search(r"[-*+]", expr):
        return str(eval(re.sub(r"k[A-Z]\w*", lambda m: str(consts[m.group(0)]), expr)))
    m = re.fullmatch(r'(\w+)\s*/\s*(\d+)', expr)
    if m: return str(consts[m.group(1)] // int(m.group(2)))
    return expr

bodies = {}
for m in re.finditer(r'struct\s+(?:alignas\(64\)\s+)?(\w+)\s*\{(.*?)\n\};', hdr, re.S):
    bodies[m.group(1)] = m.group(2)

def fields(name):
    out = []
    for line in bodies[name].split('\n'):
        line = re.sub(r'//.*', '', line).strip()
        if not line or line.startswith('static_assert'): continue
        line = line.replace('alignas(64)', '').strip()
        m = re.fullmatch(r'(std::atomic<(\w+)>|\w+)\s+(\w+)((?:\[[^\]]+\])*)\s*;', line)
        if not m: raise SystemExit(f'cannot parse {name}: {line}')
        full, inner, fname, dims = m.groups()
        if inner: base = atom[inner]
        elif full in prim: base = prim[full]
        else: base = full
        ty = base
        for d in reversed(re.findall(r'\[([^\]]+)\]', dims)):
            ty = f'[{ty}; {dim(d)}]'
        out.append((fname, ty))
    return out

order = ['RemoteCommand', 'BusHeader', 'Command', 'TimelineTag', 'SlotHeader', 'SlotTags', 'StreamOutHeader',
         'SourceHeader', 'LinkInHeader', 'FriendHeader', 'FeederRecord', 'PluginRequest', 'FeederTap',
         'BeaconHeader', 'ChannelRing', 'BusLayout']
docs = {
    'BusHeader': 'Bus header (4 KB): Hub ownership and heartbeat, consumers, remote-control queue.',
    'SlotHeader': 'Per-track slot.', 'StreamOutHeader': 'Stream outputs written by the Hub ([0] Stream Mix, [1..8] stems).',
    'SourceHeader': 'HEARASIDE App Audio instance.', 'LinkInHeader': 'Audio sent in through the Hub\'s "send to me" link.',
    'FriendHeader': 'A friend in the room (v13).', 'FeederRecord': 'A Track in "friend input" mode.',
    'PluginRequest': 'Plug-in -> Hub request (multi-writer queue).', 'FeederTap': 'Decimated mono tap of a feeder.',
    'BeaconHeader': 'Fixed-forever 64-byte beacon segment.', 'ChannelRing': 'Stereo audio FIFO.',
    'BusLayout': 'The whole shared-memory segment.', 'RemoteCommand': 'Remote control command (OBS hotkeys -> Hub).',
    'Command': 'Hub -> plug-in mailbox entry.', 'TimelineTag': 'One entry per processed block (seqlock).',
    'SlotTags': 'Timeline tags of one slot.'}
out = ['// Generated by gen_protocol.py from libs/ssbus/include/ssbus/protocol.h (v14), checked field by field against',
       '// compat/fixtures/shm-v14-layout.json (tests/layout.rs). Padding is explicit: every offset, size and',
       '// alignment equals the MSVC x64 layout of the C++ header. Do not reorder; a change is a new protocol version.',
       '#![allow(missing_docs)]', '',
       'use core::sync::atomic::{AtomicI32, AtomicI64, AtomicU32, AtomicU64};', '']
for k, v in consts.items():
    if k == 'kLayoutSize': continue
    ty = 'u32' if (v > 0x7fffffff or k in ('kMagic','kRingFrames','kRingMask','kGuardFrames','kBeaconMagic','kProtocolVersion') or k.startswith('kReply') or k == 'kPairAutomatic') else 'usize'
    out.append(f'pub const {snake(k[1:]).upper()}: {ty} = {v};')
out.append(f'/// `sizeof(BusLayout)`.\npub const LAYOUT_SIZE: usize = {consts["kLayoutSize"]};')
out.append('')
for en, vals in fix['enums'].items():
    out.append(f'/// `{en}` in protocol.h.')
    out.append(f'pub mod {snake(en)} {{')
    for k, v in vals.items():
        n = k[1:] if re.fullmatch(r'k[A-Z]\w*', k) else k
        out.append(f'    pub const {snake(n).upper()}: u32 = {v};')
    out.append('}')
    out.append('')
tests = []
for s in order:
    info = fix['structs'][s]
    align = info['alignment']
    rep = 'C, align(64)' if align == 64 else 'C'
    out.append(f'/// {docs[s]}')
    out.append(f'#[repr({rep})]')
    out.append(f'pub struct {s} {{')
    off = 0; padn = 0
    sizes = {'u8':1,'u32':4,'i32':4,'f32':4,'u64':8,'i64':8,'AtomicU32':4,'AtomicI32':4,'AtomicU64':8,'AtomicI64':8}
    for fname, ty in fields(s):
        want = info['fields'][fname]['offset']
        if want > off:
            out.append(f'    _pad{padn}: [u8; {want - off}],'); padn += 1
        rname = snake(fname)
        if rname == 'pad': rname = 'reserved_pad'
        out.append(f'    pub {rname}: {ty},')
        off = want + info['fields'][fname]['size']
        tests.append((s, fname, rname))
    if info['size'] > off:
        out.append(f'    _pad{padn}: [u8; {info["size"] - off}],')
    out.append('}')
    out.append(f'const _: () = assert!(core::mem::size_of::<{s}>() == {info["size"]});')
    out.append(f'const _: () = assert!(core::mem::align_of::<{s}>() == {align});')
    out.append('')
out.append('/// Every C++ field with its Rust offset and size: `(struct, C++ field, offset, size)`, for the layout test.')
out.append('pub fn layout_table() -> Vec<(&\'static str, &\'static str, usize, usize)> {')
out.append('    fn size<S, F>(_: fn(&S) -> &F) -> usize { core::mem::size_of::<F>() }')
out.append('    vec![')
for s, f, r in tests:
    out.append(f'        ("{s}", "{f}", core::mem::offset_of!({s}, {r}), size::<{s}, _>(|s| &s.{r})),')
out.append('    ]')
out.append('}')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
